/**
 * ============================================================================
 * 数据采集合规声明（DATA_COLLECTION_COMPLIANCE.js）
 * ----------------------------------------------------------------------------
 * 本文件是 js/login-device.js 等前端数据采集模块的合规依据文档，全部内容为
 * 注释，不含任何可执行逻辑，仅作声明与清单用途。请勿在代码中 require 本文件。
 *
 * ⚠️ 设计原则：
 *   1) 所有采集能力【默认关闭】。仅当用户在本站明确同意隐私条款（例如主动
 *      勾选/进入受保护功能）后才按需启用对应采集项。
 *   2) 每个采集项必须有明确用途，且遵循"最小必要"原则——能不用真实值就用
 *      脱敏值（如哈希/一方向值），能本地化就不上报。
 *   3) 任何采集项的开关变更必须同时更新本清单与隐私说明页。
 *   4) 生产环境应通过配置（如 xtj_user 安全设置 / 服务端下发开关）控制采集，
 *      而非在前端写死"强制采集"。
 *
 * 如需调整某项采集行为，请同步修改 login-device.js 中对应的开关分支，并在此
 * 清单中登记改动（新增条目、注明用途与默认状态）。
 * ============================================================================
 */

/* ---------------------------------------------------------------------------
 * 一、数据采集清单
 * 状态取值：OFF=默认关闭 / ON=用户同意后启用 / ALWAYS=基础设施必需（不可关闭）
 * ---------------------------------------------------------------------------
 *
 * 1) 设备指纹（Canvas / WebGL 指纹）         状态：OFF
 *    用途：登录设备识别与异常登录告警。仅在用户同意后采集，且优先使用脱敏哈希。
 *
 * 2) WebRTC 内网 IP 探测                       状态：OFF
 *    用途：识别代理/多开刷量风险。探测结果仅保存在本地，不主动上报，
 *          仅在服务端明确请求且用户同意时上报脱敏值。
 *
 * 3) 电池状态（Battery API）                  状态：OFF
 *    用途：低电量提示（纯本地体验优化），不上报。
 *
 * 4) 存储可用量（navigator.storage）          状态：OFF
 *    用途：本地缓存水位监控（纯本地），不上报。
 *
 * 5) 媒体设备枚举（getUserMedia 设备清单）    状态：OFF
 *    用途：照片/视频上传前的设备选择。仅在用户主动进入上传流程时枚举，
 *          未授权不采集，采集结果不持久化上报。
 *
 * 6) GPS 精确位置 / 地理定位                  状态：OFF
 *    用途：帖子"位置"标签（用户主动发布时选择）。仅在用户主动触发定位授权时
 *          采集，且上报前可编辑/可取消。
 *
 * 7) 剪贴板读取                              状态：OFF
 *    用途：粘贴"发送失败/乱码"反馈时的主动粘贴操作。仅在用户显式粘贴动作时
 *          触发，读取后不缓存。
 *
 * 8) 通讯录/联系人访问                       状态：OFF
 *    用途：无。本模块不采集通讯录；任何代码路径均不得发起联系人权限请求。
 *
 * 9) 行为追踪（页面停留、访问路径、点击序列） 状态：OFF
 *    用途：站内访问统计与体验优化。默认只记录匿名聚合指标；逐用户行为序列
 *          仅在用户同意后采集，且记录中剔除消息正文等敏感内容。
 *
 * 10) 登录/会话设备记录（localStorage xtj_user 等） 状态：ALWAYS
 *    用途：维持登录态与"最近访问"等基础功能，属基础设施必需。
 *          存储内容限定为用户名、会话 token、必要时间戳，不含敏感正文。
 *
 * ---------------------------------------------------------------------------
 * 二、数据上报边界
 * - 上报一律经 API_BASE 指向的站内接口，禁止直连任何第三方统计域名。
 * - 上报载荷必须最小化：能传标识符就不传原文，能传布尔就不传数值明细。
 * - 页面卸载（pagehide）场景的上报使用非阻塞方式，不得影响页面关闭。
 *
 * 三、删除与撤销
 * - 用户可随时在设置中关闭非必需采集；关闭后立即停止采集且不再回补历史。
 * - 注销账号时，服务端应一并清除本清单涉及的个人数据。
 *
 * 四、默认状态总表（实现时必须与本表一致）
 * | 采集项            | 默认状态 | 前置条件                |
 * |-------------------|---------|-------------------------|
 * | 设备指纹          | OFF     | 用户同意隐私条款        |
 * | WebRTC 内网 IP    | OFF     | 用户同意 + 服务端请求   |
 * | 电池状态          | OFF     | 无（本地）              |
 * | 存储可用量        | OFF     | 无（本地）              |
 * | 媒体设备枚举      | OFF     | 用户进入上传流程        |
 * | GPS 位置          | OFF     | 用户主动授权            |
 * | 剪贴板读取        | OFF     | 用户显式粘贴动作        |
 * | 通讯录/联系人     | OFF     | 不采集（禁止）          |
 * | 行为追踪          | OFF     | 用户同意 + 匿名化       |
 * | 会话设备记录      | ALWAYS  | 基础设施必需            |
 * ---------------------------------------------------------------------------
 */
