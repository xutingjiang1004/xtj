function fixGarbledText(text) {
    // 方法1: 尝试将文本当作 GBK 字节重新解码
    try {
        // 先获取原始错误的字节
        const buffer = Buffer.from(text, 'latin1');
        // 然后用 GBK 解码
        const decoder = new TextDecoder('gbk');
        const result = decoder.decode(buffer);
        if (result && result !== text && /[\u4e00-\u9fa5]/.test(result)) {
            return result;
        }
    } catch (e) {
        // 继续尝试其他方法
    }

    // 方法2: 尝试 GB2312
    try {
        const buffer = Buffer.from(text, 'latin1');
        const iconv = new Iconv('GB2312', 'UTF-8');
        const result = iconv.convert(buffer).toString('utf8');
        if (result && result !== text && /[\u4e00-\u9fa5]/.test(result)) {
            return result;
        }
    } catch (e) {
        // 继续尝试
    }

    return text;
}

