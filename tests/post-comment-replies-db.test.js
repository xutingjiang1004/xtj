'use strict';
const test=require('node:test'), assert=require('node:assert/strict'), fs=require('node:fs');
const {Client}=require('pg'),{randomUUID}=require('node:crypto');
const connectionString=process.env.XTJ_TEST_DATABASE_URL;

function migration(suffix){return fs.readFileSync('supabase/migrations/'+fs.readdirSync('supabase/migrations').find(x=>x.endsWith(suffix)),'utf8');}

test('comment replies: parent validation, idempotency, deletion races and backward compatibility',{skip:!connectionString,timeout:45000},async t=>{
  const url=new URL(connectionString);assert.ok(['localhost','127.0.0.1'].includes(url.hostname));
  const admin=new Client({connectionString});await admin.connect();
  const name='xtj_replies_'+randomUUID().replaceAll('-','');await admin.query('CREATE DATABASE '+name);url.pathname='/'+name;
  const db=new Client({connectionString:url.href});await db.connect();
  try {
    // Roles are cluster-global: other DB test files may be creating them at the same moment.
    for(let attempt=1;;attempt++){
      try{
        await db.query(`DO $$ BEGIN IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon; END IF;
          IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated; END IF;
          IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN CREATE ROLE service_role BYPASSRLS; END IF;
          IF NOT (SELECT rolbypassrls FROM pg_roles WHERE rolname='service_role') THEN ALTER ROLE service_role BYPASSRLS; END IF; END $$;`);
        break;
      }catch(error){if(attempt>=8||!/concurrently updated|already exists/.test(error.message))throw error;await new Promise(resolve=>setTimeout(resolve,100*attempt));}
    }
    await db.query(`
      CREATE SCHEMA xtj_private;
      CREATE FUNCTION xtj_private.safe_jsonb(text) RETURNS jsonb LANGUAGE plpgsql IMMUTABLE AS $$ BEGIN RETURN $1::jsonb; EXCEPTION WHEN OTHERS THEN RETURN '{}'::jsonb; END $$;
      CREATE TABLE posts(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_name text,media_type text,media_url text,content text,actor_key text,visibility text DEFAULT 'public',is_deleted boolean DEFAULT false,created_at timestamptz DEFAULT now(),views integer DEFAULT 0);
      CREATE TABLE comments(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,post_id uuid REFERENCES posts(id) ON DELETE CASCADE,user_name text,content text,actor_key text,created_at timestamptz DEFAULT now(),parent_comment_id bigint REFERENCES comments(id) ON DELETE CASCADE,generated_by_ai boolean DEFAULT false);
      CREATE TABLE likes(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,post_id uuid REFERENCES posts(id) ON DELETE CASCADE,user_name text,actor_key text,created_at timestamptz DEFAULT now(),UNIQUE(post_id,user_name));
      CREATE TABLE chat_users(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_name text,is_registered boolean DEFAULT true,deleted_at timestamptz);
      CREATE TABLE chat_messages(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),legacy_post_id uuid,conversation_id uuid,sent_at timestamptz DEFAULT now(),withdrawn_at timestamptz);
      CREATE TABLE chat_conversation_members(conversation_id uuid,user_id uuid,cleared_before timestamptz,left_at timestamptz);
      CREATE TABLE chat_message_user_state(message_id uuid,user_id uuid,hidden_at timestamptz);`);
    // Production order: the interaction migrations first, then the reply migration.
    await db.query(migration('_frontend_interaction_consistency.sql'));
    await db.query(migration('_interaction_identifier_precision.sql'));
    await db.query(migration('_comment_replies.sql'));
    const post=(await db.query("INSERT INTO posts(user_name,media_type,content) VALUES('alice','text','hello') RETURNING id")).rows[0].id;
    const otherPost=(await db.query("INSERT INTO posts(user_name,media_type,content) VALUES('alice','text','other') RETURNING id")).rows[0].id;
    const create=async(owner,content,{parent=null,key=randomUUID(),target=post,kind='post'}={})=>(await db.query(
      'SELECT public.xtj_create_comment($1,$2,$3,$4,$5,$6) AS body',[target,owner,content,key,kind,parent])).rows[0].body;
    let root;
    await t.test('the old five-argument call still works and is not ambiguous',async()=>{
      const legacy=(await db.query('SELECT public.xtj_create_comment($1,$2,$3,$4,$5) AS body',[post,'alice','root comment',randomUUID(),'post'])).rows[0].body;
      assert.equal(legacy.ok,true);assert.equal(legacy.comment.parent_comment_id,null);root=legacy.comment;
      const named=(await db.query('SELECT public.xtj_create_comment(p_post_id=>$1,p_owner=>$2,p_content=>$3) AS body',[post,'bob','named call'])).rows[0].body;
      assert.equal(named.ok,true);
      assert.equal((await db.query("SELECT count(*) FROM pg_proc WHERE proname='xtj_create_comment'")).rows[0].count,'1');
    });
    await t.test('a reply stores its parent and reports it as a decimal string',async()=>{
      const reply=await create('bob','reply to root',{parent:root.id});
      assert.equal(reply.ok,true);assert.equal(reply.created,true);assert.equal(reply.comment.parent_comment_id,String(root.id));
      const nested=await create('carol','reply to reply',{parent:reply.comment.id});
      assert.equal(nested.comment.parent_comment_id,String(reply.comment.id));
    });
    await t.test('missing, cross-post and photo-wall parents are rejected instead of becoming top-level comments',async()=>{
      assert.equal((await create('bob','x',{parent:'999999999'})).code,'parent_not_found');
      assert.equal((await create('bob','x',{parent:root.id,target:otherPost})).code,'parent_not_found');
      assert.equal((await create('bob','x',{parent:root.id,kind:'photo'})).code,'invalid_request');
      assert.equal((await db.query("SELECT count(*) FROM comments WHERE content='x'")).rows[0].count,'0');
    });
    await t.test('a retried reply returns the same row; a different parent for the same request is a conflict',async()=>{
      const key=randomUUID();
      const first=await create('bob','retry me',{parent:root.id,key});
      const again=await create('bob','retry me',{parent:root.id,key});
      assert.equal(again.created,false);assert.equal(again.comment.id,first.comment.id);
      assert.equal((await create('bob','retry me',{parent:first.comment.id,key})).code,'idempotency_conflict');
      assert.equal((await create('bob','retry me',{key})).code,'idempotency_conflict');
    });
    await t.test('a reply racing the deletion of its parent never leaves an orphan',async()=>{
      const parent=await create('alice','doomed parent');
      const holder=new Client({connectionString:url.href});await holder.connect();
      try{
        await holder.query('BEGIN');
        await holder.query('SELECT public.xtj_delete_comment($1,$2)',[parent.comment.id,'alice']);
        const pending=create('bob','too late',{parent:parent.comment.id});
        await new Promise(resolve=>setTimeout(resolve,50));
        await holder.query('COMMIT');
        assert.equal((await pending).code,'parent_not_found');
      } finally {await holder.end();}
      assert.equal((await db.query("SELECT count(*) FROM comments WHERE content='too late'")).rows[0].count,'0');
    });
    await t.test('deleting a parent removes every descendant reply',async()=>{
      const top=await create('alice','thread top');
      const mid=await create('bob','thread mid',{parent:top.comment.id});
      const leaf=await create('carol','thread leaf',{parent:mid.comment.id});
      const removed=(await db.query('SELECT public.xtj_delete_comment($1,$2) AS body',[top.comment.id,'alice'])).rows[0].body;
      assert.deepEqual(removed.deleted_comment_ids.sort(),[top.comment.id,mid.comment.id,leaf.comment.id].map(String).sort());
    });
    await t.test('only the backend role may call the function',async()=>{
      await db.query('SET ROLE anon');
      await assert.rejects(db.query('SELECT public.xtj_create_comment($1,$2,$3,$4,$5,$6)',[post,'alice','attack',randomUUID(),'post',null]),/permission denied/);
      await db.query('RESET ROLE');
    });
  } finally {
    await db.end().catch(()=>{});
    await admin.query('DROP DATABASE IF EXISTS '+name+' WITH (FORCE)').catch(()=>{});
    await admin.end().catch(()=>{});
  }
});
